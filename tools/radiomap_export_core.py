METHOD = "scheduled_settling_prior_status_v1"
COLUMNS = "survey_id survey_revision source_session_ref scan_id robot_id scan_time scan_time_original visit_id grid_id intended_x_m intended_y_m estimated_x_m estimated_y_m estimated_heading_deg location_mode distance_to_target_m interval_kind script_offset_s qualified exclusion_reason qualification_method ap_id radio_id band observation_status rssi_dbm bssid ssid channel_id center_frequency_mhz channel_width_mhz radio_settings_id tx_power_dbm tx_power_mode tx_power_reference radio_metadata_source radio_metadata_time scan_metadata_json observation_metadata_json".split()
